// Build: tokens/*.tokens.json -> dist/tokens.css, dist/tokens.resolved.json, docs/tokens.js
// Run: npm run build
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadTokens, cssVar, deref, toCss } from './lib.mjs';

const { base, themes, defaultTheme } = loadTokens();
const merged = Object.fromEntries(Object.entries(themes).map(([name, t]) => [name, new Map([...base, ...t])]));

// Validate: every alias resolves, every token ends in a typed value, themes define the same names.
for (const [theme, tokens] of Object.entries(merged)) {
  for (const name of tokens.keys()) {
    const end = deref(name, tokens);
    if (!end.type) throw new Error(`Token "${name}" (${theme}) has no $type, directly or inherited`);
  }
}
const themeNames = Object.keys(themes);
for (const theme of themeNames) {
  for (const name of themes[defaultTheme].keys()) {
    if (!themes[theme].has(name)) throw new Error(`Theme "${theme}" is missing token "${name}"`);
  }
  for (const name of themes[theme].keys()) {
    if (!themes[defaultTheme].has(name)) throw new Error(`Theme "${theme}" defines "${name}" but "${defaultTheme}" does not`);
  }
}

const block = (tokens, all, indent) =>
  [...tokens].map(([name, t]) => `${indent}${cssVar(name)}: ${toCss(t.value, deref(name, all).type, all, true)};`).join('\n');

const other = themeNames.filter((t) => t !== defaultTheme);
let css = `/* Generated by scripts/build-tokens.mjs. Do not edit: change tokens/*.tokens.json and rebuild. */\n`;
css += `:root {\n  color-scheme: ${defaultTheme};\n${block(base, merged[defaultTheme], '  ')}\n${block(themes[defaultTheme], merged[defaultTheme], '  ')}\n}\n`;
for (const theme of other) {
  css += `\n:root[data-theme="${theme}"] {\n  color-scheme: ${theme};\n${block(themes[theme], merged[theme], '  ')}\n}\n`;
  css += `\n@media (prefers-color-scheme: ${theme}) {\n  :root:not([data-theme]) {\n    color-scheme: ${theme};\n${block(themes[theme], merged[theme], '    ')}\n  }\n}\n`;
}

// Flat, fully resolved list for docs and for agents.
const resolved = [...merged[defaultTheme].keys()].map((name) => {
  const entry = {
    name,
    cssVar: cssVar(name),
    type: deref(name, merged[defaultTheme]).type,
    tier: name.startsWith('palette.') || base.has(name) && !/^(size|shape|border|motion|measure)\./.test(name) ? 'primitive' : 'semantic',
    description: deref(name, merged[defaultTheme]).description,
    themed: themes[defaultTheme].has(name),
  };
  for (const theme of themeNames) {
    const t = merged[theme].get(name);
    entry[theme] = toCss(t.value, entry.type, merged[theme], false);
    const alias = typeof t.value === 'string' ? t.value.slice(1, -1) : null;
    if (alias) (entry.alias ??= {})[theme] = alias;
  }
  return entry;
});

mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist/tokens.css'), css);
writeFileSync(join(ROOT, 'dist/tokens.resolved.json'), JSON.stringify(resolved, null, 2) + '\n');
writeFileSync(join(ROOT, 'docs/tokens.js'), `// Generated by scripts/build-tokens.mjs. Do not edit.\nwindow.DS_TOKENS = ${JSON.stringify(resolved)};\n`);
console.log(`Built ${resolved.length} tokens (${resolved.filter((t) => t.tier === 'primitive').length} primitive, ${resolved.filter((t) => t.tier === 'semantic').length} semantic) for themes: ${themeNames.join(', ')}`);
