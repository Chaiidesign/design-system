function cssBlocks(file) {
  const out = {};
  const text = readFileSync(join(ROOT, file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const b of text.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const sel = b[1].trim();
    for (const d of b[2].matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/g)) (out[sel] ??= {})[d[1]] = d[2].trim();
  }
  return out;
}
