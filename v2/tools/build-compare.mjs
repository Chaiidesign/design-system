// Builds the three-way comparison of version 0.2's screens and measures it.
//
//   node v2/tools/build-compare.mjs
//
// The three variants of each screen (checkout, checkout-errors, assistant, assistant-done):
//   v02       screens/<screen>.html as version 0.2 built it (read in place, never copied or changed)
//   as-given  the same page with only the V2 tokens Figma holds (v2/screens/tokens-as-given/tokens.css, built by
//             "node v2/tools/build-tokens.mjs --no-overrides --no-proposed --out v2/screens/tokens-as-given"), the
//             as-given bridge (v2/screens/bridge-as-given.css), Geist. Where Figma holds no token for a job, that bridge
//             uses a literal listed in bridge-map.json "asGiven" and shown on the comparison page.
//   merged    the same page with the V2 tokens on this branch (ds-tokens/dist/tokens.css: Figma plus the overrides and the
//             proposed tokens), the bridge (v2/screens/bridge.css), Geist
//
