//   v2/screens/bridge.css, bridge-as-given.css   from v2/screens/bridge-map.json (hand-written), checked against
//                                         dist/tokens.css and each column's own V2 token file
//   v2/screens/fonts/Geist-Variable.woff2 copied from node_modules/geist
//   v2/screens/{as-given,merged}/<screen>.html
//   v2/screens/measurements.json          per page and theme: text contrast, control edges, target size, sideways scroll,
//                                         smallest text
//   v2/screens/index.html                 the comparison page, with one line per variant from the measurements
//   digests/2026-11-16-v2/screens/<variant>-<screen>-375-<theme>.png and compare-1280-<theme>.png
