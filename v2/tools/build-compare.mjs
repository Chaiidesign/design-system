function summarise(raw) {
  const texts = raw.texts.map((t) => {
    const r = ratio(t.fg, t.bg), need = large(t) ? 3 : 4.5;
    return { text: t.text, on: t.on, ratio: r, need, size: t.size, weight: t.weight, pass: r >= need };
  });
  const controls = raw.controls.map((c) => ({ on: c.on, by: c.by, ratio: ratio(c.edge, c.beside), pass: ratio(c.edge, c.beside) >= 3 }));
  const lowest = texts.reduce((m, t) => (!m || t.ratio < m.ratio ? t : m), null);
  const targets = raw.targets.map((t) => ({ ...t, pass: t.w >= 24 && t.h >= 24 }));
  const smallestTarget = targets.reduce((m, t) => (!m || Math.min(t.w, t.h) < Math.min(m.w, m.h) ? t : m), null);
  return {
    textNodes: texts.length,
    textFails: texts.filter((t) => !t.pass).length,
    lowestText: lowest ? { ratio: lowest.ratio, need: lowest.need, text: lowest.text, on: lowest.on } : null,
    failingTexts: texts.filter((t) => !t.pass).map(({ text, on, ratio: r, need }) => ({ text, on, ratio: r, need })),
    controls: controls.length,
    controlEdgeFails: controls.filter((c) => !c.pass).length,
    lowestControl: controls.reduce((m, c) => (!m || c.ratio < m.ratio ? c : m), null),
    failingControls: controls.filter((c) => !c.pass),
    targets: targets.length,
    targetFails: targets.filter((t) => !t.pass).length,
    smallestTarget: smallestTarget ? { on: smallestTarget.on, w: smallestTarget.w, h: smallestTarget.h, by: smallestTarget.by } : null,
    failingTargets: targets.filter((t) => !t.pass).map(({ on, w, h, by }) => ({ on, w, h, by })),
    overflow: raw.overflow,
    scrollWidth: raw.scrollWidth,
    smallestText: texts.length ? Math.min(...texts.map((t) => t.size)) : null,
    skippedDisabledText: raw.skippedDisabled,
    height: raw.height,
  };
}

