const fontFace = '@font-face { font-family: "Geist"; src: url("../fonts/Geist-Variable.woff2") format("woff2"); font-weight: 100 900; font-style: normal; font-display: swap; }';
const SCREENS_DIR = join(ROOT, 'screens');
function buildPage(screen, variant) {
  const srcPath = join(SCREENS_DIR, `${screen}.html`);
  let html = readFileSync(srcPath, 'utf8');
  const pageDir = join(OUT, variant.id);
  // Every relative URL in href, src or action is re-pointed from screens/ to this folder. A link to another
  // generated screen stays inside the variant; anything else goes back to the original under screens/.
  html = html.replace(/\b(href|src|action)="([^"]*)"/g, (all, attr, url) => {
    if (!url || /^(#|[a-z][a-z0-9+.-]*:|\/)/i.test(url)) return all;
    const [path, rest = ''] = url.split(/(?=[?#])/);
    const target = resolve(SCREENS_DIR, path);
    const name = rel(target).replace(/^screens\//, '').replace(/\.html$/, '');
    const out = SCREENS.includes(name) ? `${name}.html` : posix.normalize(relative(pageDir, target).split('\\').join('/'));
    // A generated sibling is written by this run; anything else must already exist.
    if (!SCREENS.includes(name) && !existsSync(resolve(pageDir, out))) fail(`${variant.id}/${screen}.html: ${attr}="${url}" points at ${out}, which does not exist`);
    return `${attr}="${out}${rest}"`;
  });
  const tokensHref = relative(pageDir, join(ROOT, variant.tokens)).split('\\').join('/');
  const extra = [
    `<link rel="stylesheet" href="${tokensHref}">`,
    `<link rel="stylesheet" href="../${variant.bridge}">`,
    `<style>${fontFace}</style>`,
  ].join('\n');
  const before = html;
  html = html.replace(/(<link rel="stylesheet" href="[^"]*dist\/souvenir\.css">)/, `$1\n${extra}`);
  if (html === before) fail(`${screen}.html: no link to dist/souvenir.css to put the V2 stylesheets after`);
  html = html.replace(/^<!doctype html>\n/i, (d) => `${d}<!-- ${GENERATED} Source: screens/${screen}.html, with ${variant.tokens}, v2/screens/${variant.bridge} and Geist. -->\n`);
  return html;
}

// ---------- 3. Geist and Japanese: read the font's character map ----------
// Returns the code points among `cps` that the TrueType font maps to a glyph other than 0 (format 4 and 12 subtables).
function cmapCovers(file, cps) {
  const b = readFileSync(file);
  const n = b.readUInt16BE(4);
  let cmap = -1;
  for (let i = 0; i < n; i++) if (b.toString('latin1', 12 + i * 16, 16 + i * 16) === 'cmap') cmap = b.readUInt32BE(12 + i * 16 + 8);
  if (cmap < 0) throw new Error('no cmap table');
  const subs = b.readUInt16BE(cmap + 2);
  const found = new Set();
  const formats = [];
  for (let i = 0; i < subs; i++) {
    const off = cmap + b.readUInt32BE(cmap + 4 + i * 8 + 4);
    const fmt = b.readUInt16BE(off);
    formats.push(fmt);
    if (fmt === 4) {
      const segX2 = b.readUInt16BE(off + 6);
      const ends = off + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2;
      for (let s = 0; s < segX2 / 2; s++) {
        const end = b.readUInt16BE(ends + s * 2), start = b.readUInt16BE(starts + s * 2);
        const delta = b.readInt16BE(deltas + s * 2), ro = b.readUInt16BE(ranges + s * 2);
        for (const cp of cps) {
          if (cp < start || cp > end || cp > 0xffff) continue;
          let g;
          if (ro === 0) g = (cp + delta) & 0xffff;
          else { const gi = b.readUInt16BE(ranges + s * 2 + ro + (cp - start) * 2); g = gi ? (gi + delta) & 0xffff : 0; }
          if (g) found.add(cp);
        }
      }
    } else if (fmt === 12) {
      const groups = b.readUInt32BE(off + 12);
      for (let gI = 0; gI < groups; gI++) {
        const start = b.readUInt32BE(off + 16 + gI * 12), end = b.readUInt32BE(off + 20 + gI * 12), g0 = b.readUInt32BE(off + 24 + gI * 12);
        for (const cp of cps) if (cp >= start && cp <= end && g0 + (cp - start)) found.add(cp);
      }
    }
  }
  return { found, formats };
}
