// Builds the token package in ds-tokens/ from the Figma snapshot in v2/figma/.
//
//   node v2/tools/build-tokens.mjs              build, check, write; exit 0 only if every check passes
//   node v2/tools/build-tokens.mjs --self-test  plant known faults in memory and confirm the checks catch them (writes nothing)
//   node v2/tools/build-tokens.mjs --no-overrides --out v2/screens/tokens-as-given
//                                               the same build without ds-tokens/overrides.json, only the dist files, into
//                                               another folder (either option may be used alone; see "main" below)
//
// What it writes (all generated; do not edit by hand):
//   ds-tokens/primitives/{color,typography,space,radius}.tokens.json   DTCG 2025.10, one file per primitive collection
//   ds-tokens/semantic/*.tokens.json                                     DTCG 2025.10, one file per semantic collection and mode
//       color.tokens.json (light) + color.dark.tokens.json, gradient.tokens.json (light) + gradient.dark.tokens.json,
//       space.tokens.json (standard) + space.compact.tokens.json, typography.tokens.json, radius.tokens.json
//       border.tokens.json, size.tokens.json, motion.tokens.json, elevation.tokens.json (light) + elevation.dark.tokens.json
//       hold proposed tokens (see below); proposed Themes tokens go inside the colour files
//   ds-tokens/tokens.resolver.json   DTCG 2025.10 resolver document: sets plus the theme and density modifiers
//   ds-tokens/dist/tokens.css        semantic custom properties, named by the Figma WEB code syntax, resolved literals
//   ds-tokens/dist/tailwind-theme.css  Tailwind v4 "@theme inline" mapping of every semantic token that has a Tailwind namespace
//   ds-tokens/dist/tokens.json       flat array of semantic tokens for agents and other tools
// It reads ds-tokens/overrides.json (created as [] if missing) and applies each override after reading Figma.
// It reads ds-tokens/proposed/tokens.json (tokens the components need that Figma does not hold yet) and merges each one,
// marked "proposed", after checking that its name collides with no Figma variable, its alias names a colour primitive,
// and its mode keys are exactly the modes of its collection. Proposed CSS names follow expectedSyntax() in snapshot.mjs.
//
// Figma is read only through v2/tools/lib/snapshot.mjs. Colour conversion reuses scripts/lib/color.mjs.
// No network, no dependencies. The output contains no timestamps, so two runs give the same bytes.
