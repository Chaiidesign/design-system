#!/usr/bin/env node
// Lints the hand-written component code in ds-components/src/ so that nothing off-system gets in.
//
//   node v2/tools/lint-components.mjs              run the ten checks below on the repo
//   node v2/tools/lint-components.mjs --size       also bundle each component and write
//                                                  ds-components/generated/size-report.json
//   node v2/tools/lint-components.mjs --types      also write ds-components/tsconfig.json and run
//                                                  "npx tsc -p ds-components/tsconfig.json"
//   node v2/tools/lint-components.mjs --self-test  plant one fault per check in a temporary fixture
//                                                  and confirm that check, and only that check, reports it
//   --root <dir>                                   lint another tree laid out like this repo
//
// File layout this tool expects (nothing in the repo set one before it; the task brief did):
//   ds-components/specs/<slug>.spec.json             the contract
//   ds-components/src/<slug>/<slug>.tsx              the React component (other hand-written .tsx/.ts may sit beside it)
//   ds-components/src/<slug>/<slug>.css              generated by v2/tools/build-components.mjs, as are
//   ds-components/src/<slug>/<slug>.contract.ts      the typed contract and ds-components/src/styles.css
//   ds-components/src/<slug>/<slug>.extensions.css   hand-written CSS, inside @layer ds.extensions
//   ds-components/src/<slug>/<slug>.examples.tsx     one exported key per example id in the spec
//   ds-components/src/<slug>/<slug>.tests.mjs        one exported key per requirement checked by test:<id>
//   ds-components/src/index.ts                       exports every component that has source
//   ds-components/gallery/pages/**/*.tsx             gallery pages (only check 9 reads them)
// A file whose first line says "generated" and "do not edit" is a generated file. Generated files are left
// out of the hand-written checks (1, 2, 3, 5, 10 and the source side of 6) and are checked by check 4.
//
// The ten checks. Each finding is an error with a file and line; any error makes the exit code 1.
//   raw-value            no raw colour or length in *.extensions.css declarations or in hand-written *.tsx.
//                        Allowed lengths: 0, 100%, 50%, auto, 1fr, 1px inside calc(), and em or ch on the
//                        inline-size properties (text measure). Raw times (ms, s) are reported too.
//                        Unitless numbers (line-height: 1, flex: 1) and @media / @container conditions
//                        (which cannot take var()) are not checked. In .tsx, hex colours and colour
//                        functions are looked for in every string except href/to; lengths and named colours
//                        only in style={{}} values and in [bracketed] arbitrary values inside strings, so
//                        words such as "red" or "Save 20%" in content are not reported.
//   primitive-reference  every var(--x) in hand-written files names a custom property defined in
//                        ds-tokens/dist/tokens.css (or listed in tokens.json), or a component-local property
//                        --<slug>-... that the same folder declares, in its CSS or as a style={{ '--x': v }}
//                        key. A local property declared in CSS must carry that prefix and may not redefine a
//                        token. A name proposed in ds-tokens/proposed/ but not merged yet is still reported.
//   no-inline-style      style={{ ... }} in *.tsx may only set custom properties. A non-literal style
//                        expression is allowed only when it is a pass-through named style.
//   layer                every *.extensions.css is wrapped in @layer ds.extensions; any other CSS under src/
//                        must carry the generated header. When v2/tools/build-components.mjs exists and
//                        exports buildAll and loadContext, it is run in memory (nothing is written) and every
//                        generated file under src/ (<slug>.css, <slug>.contract.ts, styles.css) must equal
//                        its output byte for byte; a file for a spec that does not build, and styles.css
//                        while any spec does not build, is noted and not compared. Without that tool,
//                        only the header is checked, and a note says so.
//   logical-properties   no physical properties (left, top, margin-left, width, height, ...) and no
//                        float/clear/text-align left or right in extensions CSS.
//   slots                the hand-written component source mentions every anatomy part's data-slot value,
//                        as a string or as <SLUG>_SLOTS.<part> read from the generated contract, and sets no
//                        data-slot string the spec does not list. A part whose element is null (a Radix Root or
//                        Portal) renders nothing: it need not be mentioned, and a data-slot string naming it is an error.
//   examples-and-tests   <slug>.examples.tsx exports an object with a top-level key per example id, and
//                        <slug>.tests.mjs one with a key per test id. Nested keys do not count.
//   exports              ds-components/src/index.ts exports every component that has source.
//   one-primary-per-view in *.examples.tsx and gallery pages, one JSX tree holds at most one variant="primary".
//   focus-not-removed    no outline: none / 0 in extensions CSS without a :focus-visible rule in the same
//                        file that draws an outline.
//
// "No source yet": a spec whose folder is missing, or holds only generated files, is a note, and checks 6
// to 8 skip it. A folder with hand-written .tsx/.ts but no <slug>.tsx is an error under slots. A spec that
// is not readable or not valid against ds-components/schema/component.schema.json is a warning and is
// skipped: proving specs valid is v2/tools/check-specs.mjs's job. TSX is parsed with the installed
// typescript package; CSS with a small parser in this file that keeps line numbers.
//
